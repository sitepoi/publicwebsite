// ── SSOT CONTROL TOWER INDEX (npm run ssot:index) ───────────────────────────
// Scans _docs/deny/_feature-development-management recursively (group subfolders included),
// skips templates, helpers and empty placeholder files, and writes index.html
// listing every feature document with its version, status, decision / group /
// task counts, open risks and release count.
// Also invoked automatically by npm run rel after each release.
const { readFileSync, writeFileSync, readdirSync } = require('fs')
const { join, relative } = require('path')
const releaseContext = require('./releaseContext')

// ── ADAPT FOR YOUR PROJECT: same root as the other scripts. ────────────────
const SSOT_DIR = join(__dirname, '..', '..', '_docs', 'deny', '_feature-development-management')
const INDEX_PATH = join(SSOT_DIR, 'index.html')

function extractField(content, pattern, fallback = '') {
	const match = content.match(pattern)
	return match ? match[1].trim() : fallback
}

function buildDocumentInfo(filePath) {
	const content = readFileSync(filePath, 'utf8')
	if (!content.includes('<h1>')) return null   // empty placeholder file - not a real document yet
	const fileName = filePath.split(/[\\/]/).pop()
	const relativePath = relative(SSOT_DIR, filePath).replace(/\\/g, '/')
	const relativePathParts = relativePath.split('/')
	const groupFolder = relativePathParts.length > 1 ? relativePathParts[0] : 'root'
	const openRisks = releaseContext.getOpenRisksFromSsotDocuments().filter((risk) => risk.documentName === fileName)
	return {
		name: extractField(content, /<h1>([^<]+)<\/h1>/) || fileName.replace('.html', ''),
		fileName,
		relativePath,
		groupFolder,
		version: extractField(content, /Document version<\/th><td>([^<]+)/),
		updated: extractField(content, /Last updated<\/th><td>([^<]+)/),
		status: extractField(content, /class="doc-status[^"]*"[^>]*>([^<]+)/),
		decisionCount: (content.match(/<tr>\s*<td>D-[A-Z]+-\d+<\/td>/g) || []).length,
		groupCount: (content.match(/data-release-group="/g) || []).length,
		taskCount: (content.match(/data-task-id="/g) || []).length,
		riskCount: (content.match(/data-risk-id="/g) || []).length,
		openRiskCount: openRisks.length,
		releaseCount: (extractField(content, /<tbody id="release-log-rows">([\s\S]*?)<\/tbody>/) || '').split('<tr>').length - 1,
	}
}

function buildSsotIndex() {
	const documentInfos = []
	try {
		const walkSsotDirectory = (directoryPath) => {
			for (const entry of readdirSync(directoryPath, { withFileTypes: true })) {
				if (entry.name.startsWith('_') || entry.name === 'index.html') continue
				if (entry.isDirectory()) { walkSsotDirectory(join(directoryPath, entry.name)); continue }
				if (entry.isFile() && entry.name.endsWith('.html')) {
					const documentInfo = buildDocumentInfo(join(directoryPath, entry.name))
					if (documentInfo) documentInfos.push(documentInfo)
				}
			}
		}
		walkSsotDirectory(SSOT_DIR)
	} catch (_e) { /* folder missing - empty index */ }

	const totalOpenRisks = documentInfos.reduce((sum, info) => sum + info.openRiskCount, 0)
	const rows = documentInfos.map((info) => [
		'<tr>',
		'<td><a href="' + info.relativePath + '">' + info.name + '</a></td>',
		'<td>' + info.groupFolder + '</td>',
		'<td>' + info.version + '</td>',
		'<td>' + info.updated + '</td>',
		'<td>' + info.status + '</td>',
		'<td>' + info.decisionCount + '</td>',
		'<td>' + info.groupCount + '</td>',
		'<td>' + info.taskCount + '</td>',
		'<td>' + info.openRiskCount + '/' + info.riskCount + '</td>',
		'<td>' + info.releaseCount + '</td>',
		'</tr>',
	].join(''))

	const indexHtml = [
		'<!DOCTYPE html>',
		'<html lang="en">',
		'<head>',
		'<meta charset="UTF-8" />',
		'<title>SSOT Feature Index</title>',
		'<link rel="stylesheet" type="text/css" href="ssot.css" />',
		'<script src="ssot.js" defer="defer"></script>',
		'</head>',
		'<body>',
		'<div id="content" style="margin-left:0; margin-right:0;">',
		'<h1>SSOT - feature control tower</h1>',
		'<p class="meta">Generated by <code>npm run ssot:index</code> on ' + new Date().toISOString().slice(0, 10) + '. Open risks across all features: <strong>' + totalOpenRisks + '</strong>.</p>',
		'<table>',
		'<tr><th>Feature</th><th>Group</th><th>Version</th><th>Updated</th><th>Status</th><th>Decisions</th><th>Groups</th><th>Tasks</th><th>Open risks</th><th>Releases</th></tr>',
		rows,
		'</table>',
		'</div>',
		'</body>',
		'</html>',
	].join('\n')

	writeFileSync(INDEX_PATH, indexHtml, 'utf8')
	console.log('→ SSOT index written to ' + INDEX_PATH + ' (' + documentInfos.length + ' feature documents)')
}

if (require.main === module) {
	buildSsotIndex()
}

module.exports = { buildSsotIndex }
